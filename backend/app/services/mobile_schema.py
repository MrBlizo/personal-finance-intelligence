"""Generate the database schema the PFI phone app uses.

The phone app keeps the same SQLite tables as the PC, so sync can exchange
raw column values. This module writes, from the ORM models:

* ``schema.sql``: the ``CREATE TABLE``/index/trigger statements;
* ``schema.json``: what the phone's sync engine and forms need to know
  (table order, foreign keys, natural keys, money scales, defaults).

Run ``python -m app.services.mobile_schema <folder>`` after changing a
model; ``tests/test_mobile_schema.py`` fails while the copy in
``mobile/assets/db`` is out of date.
"""
from __future__ import annotations

import json
import sys
from decimal import Decimal
from pathlib import Path

from sqlalchemy import Boolean, Date, DateTime
from sqlalchemy.dialects import sqlite
from sqlalchemy.schema import CreateIndex, CreateTable

from .. import models
from ..db import Base
from ..migrations import _NEW_UID, _NOW
from . import sync

#: Bookkeeping tables the phone needs besides the synced ones.
LOCAL_TABLES = ("settings", "import_batches", "sync_tombstones",
                "sync_state", "sync_seen", "sync_aliases", "sync_pending")
SCHEMA_VERSION = 7


def _tables() -> list[str]:
    keep = set(sync.sync_tables()) | set(LOCAL_TABLES)
    return [t.name for t in Base.metadata.sorted_tables if t.name in keep]


def build_sql() -> str:
    """Return the SQL that creates the phone database."""
    dialect = sqlite.dialect()
    out = [f"-- Generated by app/services/mobile_schema.py "
           f"(PC schema v{SCHEMA_VERSION}). Do not edit.",
           "PRAGMA foreign_keys = ON;"]
    for name in _tables():
        table = Base.metadata.tables[name]
        out.append(str(CreateTable(table).compile(dialect=dialect)).strip()
                   + ";")
        for index in sorted(table.indexes, key=lambda i: i.name or ""):
            out.append(str(CreateIndex(index).compile(dialect=dialect))
                       .replace("CREATE INDEX", "CREATE INDEX IF NOT EXISTS")
                       .replace("CREATE UNIQUE INDEX",
                                "CREATE UNIQUE INDEX IF NOT EXISTS") + ";")
    for t in sync.sync_tables():
        out.append(f"CREATE UNIQUE INDEX IF NOT EXISTS ux_{t}_uid "
                   f"ON {t} (uid);")
        out.append(
            f"CREATE TRIGGER IF NOT EXISTS trg_{t}_ins AFTER INSERT ON {t} "
            f"WHEN NEW.uid IS NULL OR NEW.updated_at IS NULL BEGIN "
            f"UPDATE {t} SET uid = coalesce(NEW.uid, {_NEW_UID}), "
            f"updated_at = coalesce(NEW.updated_at, {_NOW}) "
            f"WHERE rowid = NEW.rowid; END;")
        out.append(
            f"CREATE TRIGGER IF NOT EXISTS trg_{t}_upd AFTER UPDATE ON {t} "
            f"WHEN NEW.updated_at IS OLD.updated_at BEGIN "
            f"UPDATE {t} SET updated_at = {_NOW} WHERE rowid = NEW.rowid; "
            f"END;")
        out.append(
            f"CREATE TRIGGER IF NOT EXISTS trg_{t}_del AFTER DELETE ON {t} "
            f"WHEN OLD.uid IS NOT NULL BEGIN "
            f"INSERT INTO sync_tombstones (table_name, uid, deleted_at) "
            f"VALUES ('{t}', OLD.uid, {_NOW}); END;")
    return "\n\n".join(out) + "\n"


def _raw_default(col):
    d = col.default
    if d is None or not d.is_scalar:
        return None
    v = d.arg
    if isinstance(v, bool):
        return int(v)
    if isinstance(col.type, models.ExactDecimal):
        return int(Decimal(str(v)) * (Decimal(10) ** col.type.scale))
    if isinstance(v, (int, float, str)):
        return v
    return None


def build_meta() -> dict:
    """Return the table facts the phone's sync engine and forms use."""
    tables = sync.sync_tables()
    meta: dict = {"format": sync.FORMAT, "schema": SCHEMA_VERSION,
                  "tables": tables, "has_id": {}, "columns": {}, "fks": {},
                  "unique": {}, "money": {}, "bool": {}, "date": {},
                  "datetime": {}, "defaults": {}, "required": {}}
    for t in tables:
        tbl = Base.metadata.tables[t]
        meta["has_id"][t] = sync._has_id(t)
        meta["columns"][t] = [c.name for c in tbl.columns]
        meta["fks"][t] = {k: (list(v) if v else None)
                          for k, v in sync._fks(t).items()}
        meta["unique"][t] = [list(k) for k in sync._unique_keys(t)]
        meta["money"][t] = {c.name: c.type.scale for c in tbl.columns
                            if isinstance(c.type, models.ExactDecimal)}
        meta["bool"][t] = [c.name for c in tbl.columns
                           if isinstance(c.type, Boolean)]
        meta["date"][t] = [c.name for c in tbl.columns
                           if isinstance(c.type, Date)
                           and not isinstance(c.type, DateTime)]
        meta["datetime"][t] = [c.name for c in tbl.columns
                               if isinstance(c.type, DateTime)]
        meta["defaults"][t] = {c.name: v for c in tbl.columns
                               if (v := _raw_default(c)) is not None}
        meta["required"][t] = [
            c.name for c in tbl.columns
            if not c.nullable and not c.primary_key and c.default is None
            and c.server_default is None and c.name not in
            ("uid", "updated_at")]
    return meta


def write(folder: Path) -> None:
    """Write ``schema.sql`` and ``schema.json`` into ``folder``.

    Parameters
    ----------
    folder : Path
        The output folder, normally ``mobile/assets/db``.
    """
    folder = Path(folder)
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "schema.sql").write_text(build_sql(), encoding="utf-8",
                                       newline="\n")
    (folder / "schema.json").write_text(
        json.dumps(build_meta(), indent=1, sort_keys=True) + "\n",
        encoding="utf-8", newline="\n")


if __name__ == "__main__":  # pragma: no cover
    write(Path(sys.argv[1] if len(sys.argv) > 1
               else "../mobile/assets/db"))
